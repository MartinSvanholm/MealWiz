-- MEA-139: the order of the grocery list's sections, learned from shopping or set by hand.
-- - grocery_items.picked_at: when an item was ticked off (null while it is to buy), so a shopping trip can be seen.
-- - grocery_categories.order_score: the learned, fractional place of a category (null = its position). Learning nudges
--   it a little per trip, so one odd trip doesn't reorder the list.
-- - grocery_list_settings: one row per user. order_mode is learned until the user drags the sections into an order;
--   learned_until is the last tick already learned from. No row = learned, nothing learned yet.
-- - reorder_grocery_categories and apply_learned_section_order each write in one transaction (ARCHITECTURE.md,
--   "Multi-step writes"). SECURITY INVOKER, so RLS still decides what the caller may touch.

alter table public.grocery_items add column picked_at timestamptz null;

alter table public.grocery_categories add column order_score double precision null;

create table public.grocery_list_settings (
    id bigint generated by default as identity primary key,
    created_by uuid not null references auth.users(id) on update cascade on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz null,
    order_mode text not null default 'learned',
    learned_until timestamptz null,
    constraint grocery_list_settings_created_by_key unique (created_by),
    constraint grocery_list_settings_order_mode_check check (order_mode in ('learned', 'manual'))
);

alter table public.grocery_list_settings owner to postgres;

alter table public.grocery_list_settings enable row level security;

create policy "Enable users to view their own data only"
    on public.grocery_list_settings
    for select
    to authenticated
    using (((select auth.uid() as uid) = created_by));

create policy "Enable insert for users based on user_id"
    on public.grocery_list_settings
    for insert
    to authenticated
    with check (((select auth.uid() as uid) = created_by));

create policy "Enable update for users based on user_id"
    on public.grocery_list_settings
    for update
    to authenticated
    using (((select auth.uid() as uid) = created_by))
    with check (((select auth.uid() as uid) = created_by));

create policy "Enable delete for users based on user_id"
    on public.grocery_list_settings
    for delete
    to authenticated
    using (((select auth.uid() as uid) = created_by));

grant all on table public.grocery_list_settings to authenticated, service_role;
grant all on sequence public.grocery_list_settings_id_seq to authenticated, service_role;
-- Supabase's default privileges grant anon on every new table; a signed-out caller has no use for this one.
revoke all on table public.grocery_list_settings from anon;
revoke all on sequence public.grocery_list_settings_id_seq from anon;

-- ReorderGroceryCategories: the user's own order. Every one of the caller's categories must be listed, once, and
-- nothing else; positions follow the list (1-based), learned scores are dropped and learning stops (manual mode).
create function public.reorder_grocery_categories(category_ids bigint[])
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
    caller uuid := auth.uid();
    owned integer;
    changed integer;
begin
    if caller is null then
        raise exception 'not_signed_in' using errcode = '42501';
    end if;

    select count(*) into owned from public.grocery_categories where created_by = caller;
    if owned <> coalesce(array_length(category_ids, 1), 0)
        or owned <> (select count(distinct x) from unnest(category_ids) as x) then
        raise exception 'grocery_category_not_found' using errcode = 'P0002';
    end if;

    update public.grocery_categories c
    set position = o.ordinality, order_score = null, updated_at = now()
    from unnest(category_ids) with ordinality as o(id, ordinality)
    where c.id = o.id and c.created_by = caller;
    get diagnostics changed = row_count;
    if changed <> owned then
        raise exception 'grocery_category_not_found' using errcode = 'P0002';
    end if;

    insert into public.grocery_list_settings (created_by, order_mode, updated_at)
    values (caller, 'manual', now())
    on conflict (created_by) do update set order_mode = 'manual', updated_at = now();
end;
$$;

-- ApplyLearnedSectionOrder: what one or more shopping trips taught. category_scores:
-- [{"id": 1, "position": 2, "score": 1.65}, ...]. Moves learned_until so those ticks aren't learned again.
create function public.apply_learned_section_order(category_scores jsonb, learned_until timestamptz)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
    caller uuid := auth.uid();
    changed integer;
begin
    if caller is null then
        raise exception 'not_signed_in' using errcode = '42501';
    end if;

    update public.grocery_categories c
    set position = s.position, order_score = s.score, updated_at = now()
    from jsonb_to_recordset(category_scores) as s(id bigint, position integer, score double precision)
    where c.id = s.id;
    get diagnostics changed = row_count;
    if changed <> jsonb_array_length(category_scores) then
        raise exception 'grocery_category_not_found' using errcode = 'P0002';
    end if;

    insert into public.grocery_list_settings (created_by, learned_until, updated_at)
    values (caller, apply_learned_section_order.learned_until, now())
    on conflict (created_by) do update
        set learned_until = excluded.learned_until, updated_at = now();
end;
$$;

revoke all on function public.reorder_grocery_categories(bigint[]) from public, anon;
revoke all on function public.apply_learned_section_order(jsonb, timestamptz) from public, anon;
grant execute on function public.reorder_grocery_categories(bigint[]) to authenticated, service_role;
grant execute on function public.apply_learned_section_order(jsonb, timestamptz) to authenticated, service_role;
