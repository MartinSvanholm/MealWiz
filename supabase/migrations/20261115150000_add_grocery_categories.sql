-- MEA-137: the supermarket sections the grocery list is grouped into.
-- - One row per user and category. The eleven defaults carry a default_key (the app shows their name in the UI
--   language while name is null); a category the user adds has no key and a name. position orders the sections.
-- - Unique on (created_by, default_key), NULLs distinct: a user has each default at most once, so two devices
--   creating the defaults at once leave one set (the app inserts with "on conflict do nothing").
-- - A category is never stored on a grocery item or an ingredient: the app resolves it from the name.
-- Owner-only RLS for every operation; anon holds no privilege.

create table public.grocery_categories (
    id bigint generated by default as identity primary key,
    created_by uuid not null references auth.users(id) on update cascade on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz null,
    default_key text null,
    name text null,
    emoji text null,
    position int not null,
    constraint grocery_categories_default_key_check check (default_key in (
        'produce', 'bakery', 'meat_fish', 'deli', 'dairy_eggs', 'frozen', 'pantry', 'drinks', 'snacks',
        'household', 'other')),
    constraint grocery_categories_key_or_name_check check (default_key is not null or name is not null),
    constraint grocery_categories_created_by_default_key_key unique (created_by, default_key)
);

alter table public.grocery_categories owner to postgres;

create index grocery_categories_created_by_idx on public.grocery_categories (created_by);

alter table public.grocery_categories enable row level security;

create policy "Enable users to view their own data only"
    on public.grocery_categories
    for select
    to authenticated
    using (((select auth.uid() as uid) = created_by));

create policy "Enable insert for users based on user_id"
    on public.grocery_categories
    for insert
    to authenticated
    with check (((select auth.uid() as uid) = created_by));

create policy "Enable update for users based on user_id"
    on public.grocery_categories
    for update
    to authenticated
    using (((select auth.uid() as uid) = created_by))
    with check (((select auth.uid() as uid) = created_by));

create policy "Enable delete for users based on user_id"
    on public.grocery_categories
    for delete
    to authenticated
    using (((select auth.uid() as uid) = created_by));

grant all on table public.grocery_categories to authenticated, service_role;
grant all on sequence public.grocery_categories_id_seq to authenticated, service_role;
-- Supabase's default privileges grant anon on every new table; a signed-out caller has no use for this one.
revoke all on table public.grocery_categories from anon;
revoke all on sequence public.grocery_categories_id_seq from anon;
