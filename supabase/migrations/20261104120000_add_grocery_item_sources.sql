-- MEA-84: remember which planned day and ingredient a grocery item came from.
-- - grocery_items.is_manual: true for items typed by hand and for every item that exists today (no backfill);
--   the app writes false for items added from the meal plan.
-- - grocery_item_sources: one row per (planned day, ingredient) an item was added or merged from, with the amount at
--   the time. Unique on (fk_planned_meal, fk_ingredient), NULLs distinct, so a source whose planned day or
--   ingredient was deleted (set null) never collides.
-- INSERT and UPDATE require the user's own item, planned day and ingredient (planned day and ingredient may be null).
-- FK checks bypass RLS, so the policies check the parents themselves (see MEA-30).

alter table public.grocery_items add column is_manual boolean not null default true;

create table public.grocery_item_sources (
    id bigint generated by default as identity primary key,
    created_by uuid not null references auth.users(id) on update cascade on delete cascade,
    created_at timestamptz not null default now(),
    fk_grocery_item bigint not null references public.grocery_items(id) on delete cascade,
    fk_planned_meal bigint null references public."meal_plans-meals"(id) on delete set null,
    fk_ingredient bigint null references public.ingredients(id) on delete set null,
    amount text not null default '',
    constraint grocery_item_sources_planned_meal_ingredient_key unique (fk_planned_meal, fk_ingredient)
);

alter table public.grocery_item_sources owner to postgres;

create index grocery_item_sources_fk_grocery_item_idx on public.grocery_item_sources (fk_grocery_item);
create index grocery_item_sources_fk_ingredient_idx on public.grocery_item_sources (fk_ingredient);
create index grocery_item_sources_created_by_idx on public.grocery_item_sources (created_by);

alter table public.grocery_item_sources enable row level security;

create policy "Enable users to view their own data only"
    on public.grocery_item_sources
    for select
    to authenticated
    using (((select auth.uid() as uid) = created_by));

create policy "Enable insert for users based on user_id"
    on public.grocery_item_sources
    for insert
    to authenticated
    with check (
        ((select auth.uid() as uid) = created_by)
        and exists (
            select 1 from public.grocery_items g
            where g.id = fk_grocery_item and g.created_by = (select auth.uid() as uid)
        )
        and (fk_planned_meal is null or exists (
            select 1 from public."meal_plans-meals" pm
            where pm.id = fk_planned_meal and pm.created_by = (select auth.uid() as uid)
        ))
        and (fk_ingredient is null or exists (
            select 1 from public.ingredients i
            where i.id = fk_ingredient and i.created_by = (select auth.uid() as uid)
        ))
    );

create policy "Enable update for users based on user_id"
    on public.grocery_item_sources
    for update
    to authenticated
    using (((select auth.uid() as uid) = created_by))
    with check (
        ((select auth.uid() as uid) = created_by)
        and exists (
            select 1 from public.grocery_items g
            where g.id = fk_grocery_item and g.created_by = (select auth.uid() as uid)
        )
        and (fk_planned_meal is null or exists (
            select 1 from public."meal_plans-meals" pm
            where pm.id = fk_planned_meal and pm.created_by = (select auth.uid() as uid)
        ))
        and (fk_ingredient is null or exists (
            select 1 from public.ingredients i
            where i.id = fk_ingredient and i.created_by = (select auth.uid() as uid)
        ))
    );

create policy "Enable delete for users based on user_id"
    on public.grocery_item_sources
    for delete
    to authenticated
    using (((select auth.uid() as uid) = created_by));

grant all on table public.grocery_item_sources to anon, authenticated, service_role;
grant all on sequence public.grocery_item_sources_id_seq to anon, authenticated, service_role;
