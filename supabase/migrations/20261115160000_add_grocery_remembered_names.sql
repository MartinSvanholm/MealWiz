-- MEA-138: correcting and managing grocery categories.
-- - grocery_remembered_names: one row per user and normalised grocery name, pointing at the category the user put it
--   in. It beats the built-in dictionary, so a name has one category everywhere.
-- - grocery_categories.absorbed_keys: when a category is deleted, the category that takes over its items absorbs its
--   default key (and the keys it had absorbed), so dictionary words that pointed at it land there.
-- - A category name is unique per user, ignoring case; an emoji is at most 16 characters.
-- - add_grocery_category and delete_grocery_category each do a multi-step write in one transaction (ARCHITECTURE.md,
--   "Multi-step writes"). SECURITY INVOKER, so RLS still decides what the caller may touch.

alter table public.grocery_categories
    add column absorbed_keys text[] not null default '{}',
    add constraint grocery_categories_absorbed_keys_check check (absorbed_keys <@ array[
        'produce', 'bakery', 'meat_fish', 'deli', 'dairy_eggs', 'frozen', 'pantry', 'drinks', 'snacks',
        'household', 'other']::text[]),
    add constraint grocery_categories_emoji_check check (emoji is null or char_length(emoji) <= 16);

create unique index grocery_categories_created_by_name_key
    on public.grocery_categories (created_by, lower(name))
    where name is not null;

create table public.grocery_remembered_names (
    id bigint generated by default as identity primary key,
    created_by uuid not null references auth.users(id) on update cascade on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz null,
    name text not null,
    fk_category bigint not null references public.grocery_categories(id) on delete cascade,
    constraint grocery_remembered_names_created_by_name_key unique (created_by, name)
);

alter table public.grocery_remembered_names owner to postgres;

create index grocery_remembered_names_fk_category_idx on public.grocery_remembered_names (fk_category);

alter table public.grocery_remembered_names enable row level security;

-- INSERT and UPDATE also require the user's own category. FK checks bypass RLS, so the policies check it (see MEA-30).
create policy "Enable users to view their own data only"
    on public.grocery_remembered_names
    for select
    to authenticated
    using (((select auth.uid() as uid) = created_by));

create policy "Enable insert for users based on user_id"
    on public.grocery_remembered_names
    for insert
    to authenticated
    with check (
        ((select auth.uid() as uid) = created_by)
        and exists (
            select 1 from public.grocery_categories c
            where c.id = fk_category and c.created_by = (select auth.uid() as uid)
        )
    );

create policy "Enable update for users based on user_id"
    on public.grocery_remembered_names
    for update
    to authenticated
    using (((select auth.uid() as uid) = created_by))
    with check (
        ((select auth.uid() as uid) = created_by)
        and exists (
            select 1 from public.grocery_categories c
            where c.id = fk_category and c.created_by = (select auth.uid() as uid)
        )
    );

create policy "Enable delete for users based on user_id"
    on public.grocery_remembered_names
    for delete
    to authenticated
    using (((select auth.uid() as uid) = created_by));

grant all on table public.grocery_remembered_names to authenticated, service_role;
grant all on sequence public.grocery_remembered_names_id_seq to authenticated, service_role;
-- Supabase's default privileges grant anon on every new table; a signed-out caller has no use for this one.
revoke all on table public.grocery_remembered_names from anon;
revoke all on sequence public.grocery_remembered_names_id_seq from anon;

-- AddGroceryCategory: insert a category just above Other (at Other's position) and move Other, and anything after
-- it, down by one. Without an Other row the category goes last. Returns the new id.
create function public.add_grocery_category(category_name text, category_emoji text)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
    caller uuid := auth.uid();
    other_position integer;
    new_id bigint;
begin
    if caller is null then
        raise exception 'not_signed_in' using errcode = '42501';
    end if;

    select position into other_position
    from public.grocery_categories
    where created_by = caller and default_key = 'other'
    for update;

    if other_position is null then
        select coalesce(max(position), 0) + 1 into other_position
        from public.grocery_categories
        where created_by = caller;
    else
        update public.grocery_categories
        set position = position + 1, updated_at = now()
        where created_by = caller and position >= other_position;
    end if;

    insert into public.grocery_categories (created_by, name, emoji, position)
    values (caller, category_name, nullif(btrim(category_emoji), ''), other_position)
    returning id into new_id;

    return new_id;
end;
$$;

-- DeleteGroceryCategory: hand a category's remembered names and default keys to another category, then delete it.
-- Refuses Other, the same id twice, and ids the caller can't see (another user's, or gone).
create function public.delete_grocery_category(category_id bigint, move_to_id bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
    deleted public.grocery_categories%rowtype;
    target public.grocery_categories%rowtype;
begin
    if category_id = move_to_id then
        raise exception 'grocery_category_same' using errcode = 'P0001';
    end if;

    select * into deleted from public.grocery_categories where id = category_id for update;
    if not found then
        raise exception 'grocery_category_not_found' using errcode = 'P0002';
    end if;
    if deleted.default_key = 'other' then
        raise exception 'grocery_category_is_other' using errcode = 'P0001';
    end if;

    select * into target from public.grocery_categories where id = move_to_id for update;
    if not found then
        raise exception 'grocery_category_not_found' using errcode = 'P0002';
    end if;

    update public.grocery_remembered_names
    set fk_category = move_to_id, updated_at = now()
    where fk_category = category_id;

    update public.grocery_categories
    set absorbed_keys = array(
            select distinct k
            from unnest(target.absorbed_keys || deleted.absorbed_keys
                        || coalesce(array[deleted.default_key], '{}'::text[])) as k
            where k is not null and k is distinct from target.default_key
            order by k),
        updated_at = now()
    where id = move_to_id;

    delete from public.grocery_categories where id = category_id;
end;
$$;

revoke all on function public.add_grocery_category(text, text) from public, anon;
revoke all on function public.delete_grocery_category(bigint, bigint) from public, anon;
grant execute on function public.add_grocery_category(text, text) to authenticated, service_role;
grant execute on function public.delete_grocery_category(bigint, bigint) to authenticated, service_role;
